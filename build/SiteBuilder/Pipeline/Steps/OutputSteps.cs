using System.Text;
using SiteBuilder.Rendering;

namespace SiteBuilder.Pipeline.Steps;

/// <summary>
/// Empties the output folder and copies the hand-written site (HTML, CSS, JS, images, PDFs) into it.
/// Source-only files (content, the builder, docs, git) are left behind.
/// </summary>
public sealed class CopyStaticFilesStep : IBuildStep
{
    /// <summary>Top-level entries that are not part of the website.</summary>
    internal static readonly HashSet<string> ExcludedTopLevel = new(StringComparer.OrdinalIgnoreCase)
    {
        ".git", ".github", ".gitignore", ".vs", ".vscode", ".idea",
        "build", "content", "dist", "node_modules",
        "sitemap.xml", // generated by WriteSitemapStep
    };

    private static readonly HashSet<string> ExcludedAnywhere = new(StringComparer.OrdinalIgnoreCase) { "bin", "obj" };

    public string Name => "Copy static files";

    public void Execute(BuildContext context)
    {
        var root = Path.GetFullPath(context.Options.RootDirectory);
        var output = Path.GetFullPath(context.Options.OutputDirectory);

        // Never delete the source by accident.
        if (root.StartsWith(output.TrimEnd(Path.DirectorySeparatorChar) + Path.DirectorySeparatorChar, StringComparison.Ordinal)
            || root == output)
        {
            throw new BuildException($"Output folder {output} must not be the source folder or contain it.");
        }

        if (Directory.Exists(output))
        {
            Directory.Delete(output, recursive: true);
        }

        Directory.CreateDirectory(output);

        var copied = 0;
        // Snapshot the listing first: the output folder may live inside the root.
        foreach (var entry in new DirectoryInfo(root).GetFileSystemInfos())
        {
            if (ExcludedTopLevel.Contains(entry.Name)
                || Path.GetFullPath(entry.FullName).TrimEnd(Path.DirectorySeparatorChar) == output.TrimEnd(Path.DirectorySeparatorChar)
                || (entry is FileInfo && entry.Extension.Equals(".md", StringComparison.OrdinalIgnoreCase)))
            {
                continue;
            }

            copied += entry switch
            {
                DirectoryInfo dir => CopyDirectory(dir, Path.Combine(output, dir.Name)),
                FileInfo file => CopyFile(file, Path.Combine(output, file.Name)),
                _ => 0,
            };
        }

        context.Log($"  {copied} file(s)");
    }

    internal static int CopyDirectory(DirectoryInfo source, string target)
    {
        if (ExcludedAnywhere.Contains(source.Name))
        {
            return 0;
        }

        Directory.CreateDirectory(target);
        var count = source.EnumerateFiles().Sum(f => CopyFile(f, Path.Combine(target, f.Name)));
        return count + source.EnumerateDirectories().Sum(d => CopyDirectory(d, Path.Combine(target, d.Name)));
    }

    private static int CopyFile(FileInfo file, string target)
    {
        file.CopyTo(target, overwrite: true);
        return 1;
    }
}

/// <summary>Writes <c>/articles/&lt;id&gt;/index.html</c> plus the files next to each article's index.md.</summary>
public sealed class RenderArticlesStep : IBuildStep
{
    public string Name => "Render articles";

    public void Execute(BuildContext context)
    {
        foreach (var article in context.RenderedArticles)
        {
            var folder = context.OutputPath("articles", article.Id);
            Directory.CreateDirectory(folder);

            foreach (var asset in Directory.EnumerateFiles(article.SourceDirectory)
                         .Where(f => !Path.GetFileName(f).Equals("index.md", StringComparison.OrdinalIgnoreCase)))
            {
                File.Copy(asset, Path.Combine(folder, Path.GetFileName(asset)), overwrite: true);
            }

            var html = ArticlePage.Render(article, context.Options);
            File.WriteAllText(Path.Combine(folder, "index.html"), html);
            context.Log($"  {article.Path}");
        }
    }
}

/// <summary>Fills the <c>&lt;!-- build:name --&gt;</c> regions in the copied index.html from content.</summary>
public sealed class RenderHomeStep : IBuildStep
{
    public string Name => "Render home page sections";

    public void Execute(BuildContext context)
    {
        var path = context.OutputPath("index.html");
        if (!File.Exists(path))
        {
            throw new BuildException("index.html was not found in the output. Is the root folder correct?");
        }

        var profile = context.Content.Profile
            ?? throw new BuildException("content/profile.json is missing: the page title, header and metadata come from it.");
        var html = File.ReadAllText(path);

        html = Regions.Replace(html, "meta", ProfileSections.Meta(profile));
        html = Regions.Replace(html, "social", ProfileSections.Social(profile));
        html = Regions.Replace(html, "jsonld", ProfileSections.JsonLd(profile, context.Options.SiteUrl));
        html = Regions.Replace(html, "profile", ProfileSections.Header(profile));
        html = Regions.Replace(html, "links", ProfileSections.LinkButtons(context.ListedLinks));
        html = Regions.Replace(html, "intro", context.Content.IntroHtml);
        html = Regions.Replace(html, "skills", ProfileSections.Skills(context.ListedSkills));
        html = Regions.Replace(html, "about", context.Content.AboutHtml);
        html = Regions.Replace(html, "competencies", ProfileSections.Competencies(context.ListedCompetencies));
        html = Regions.Replace(html, "education", ProfileSections.Education(context.ListedEducation));
        html = Regions.Replace(html, "copyright", ProfileSections.Copyright(profile, context.Options.Today));
        html = Regions.Replace(html, "articles", HomeSections.ArticleCards(context.ListedArticles));
        html = Regions.Replace(html, "certifications", HomeSections.Certifications(context.ListedCertifications));
        html = Regions.Replace(html, "projects", HomeSections.Projects(context.ListedProjects));
        File.WriteAllText(path, html);
    }
}

/// <summary>Generates sitemap.xml from the home page and every listed article.</summary>
public sealed class WriteSitemapStep : IBuildStep
{
    public string Name => "Write sitemap";

    public void Execute(BuildContext context)
    {
        var site = context.Options.SiteUrl.TrimEnd('/');
        var xml = new StringBuilder()
            .AppendLine("""<?xml version="1.0" encoding="UTF-8"?>""")
            .AppendLine("""<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">""")
            .AppendLine($"    <url><loc>{site}/</loc><changefreq>monthly</changefreq></url>");

        foreach (var article in context.ListedArticles)
        {
            xml.AppendLine($"    <url><loc>{site}{article.Path}</loc><lastmod>{article.Date:yyyy-MM-dd}</lastmod></url>");
        }

        xml.AppendLine("</urlset>");
        File.WriteAllText(context.OutputPath("sitemap.xml"), xml.ToString());
    }
}
